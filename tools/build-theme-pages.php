<?php

/**
 * Builds src/Resources/assets/css/mm-theme-pages.css.
 *
 * mm-theme.css restyles what Mining Manager's pages share (cards, tables,
 * tiles, buttons...). Many pages also carry their own styles, in the base
 * stylesheet and in inline <style> blocks, with the original look's colours
 * written out: purple accents (#667eea, #764ba2), slate panels (#2d3748,
 * #23262d...) and purple tints (rgba(102,126,234,x)). This script finds every
 * such declaration and writes an override that puts the EVE-RO colours in
 * its place, scoped to the plugin's page wrappers, so those pages follow the
 * theme without editing each one.
 *
 * Run after changing a page's styles:   php tools/build-theme-pages.php
 * tests/Unit/ThemePagesCssTest.php fails while the file is out of date.
 */

namespace MiningManager\Tools;

final class ThemePagesBuilder
{
    /** Colour literal (lower case, no spaces) => replacement, per kind of property. */
    private const ACCENT = [
        '#667eea' => 'var(--mmx-blue)',
        '#764ba2' => 'var(--mmx-blue-deep)',
        '#4e73df' => 'var(--mmx-blue)',
        '#5a67d8' => 'var(--mmx-blue)',
        '#007bff' => 'var(--mmx-blue)',
        '#0056b3' => 'var(--mmx-blue-deep)',
    ];

    /** Panel colours, replaced only in backgrounds. */
    private const PANEL = [
        // Grounds and panels of the original look: the theme's surface.
        '#0f1115' => 'var(--mmx-surface)',
        '#161922' => 'var(--mmx-surface)',
        '#1a1d24' => 'var(--mmx-surface)',
        '#1a202c' => 'var(--mmx-surface)',
        '#212529' => 'var(--mmx-surface)',
        '#1e2129' => 'var(--mmx-surface)',
        '#23262d' => 'var(--mmx-surface)',
        '#252a33' => 'var(--mmx-surface)',
        '#2c3e50' => 'var(--mmx-surface)',
        '#2d3748' => 'var(--mmx-surface)',
        // Its lighter insets and controls: one step up.
        '#2c3138' => 'var(--mmx-surface-2)',
        '#343a40' => 'var(--mmx-surface-2)',
        '#3a3f47' => 'var(--mmx-surface-2)',
        '#454d55' => 'var(--mmx-surface-3)',
        '#4a5568' => 'var(--mmx-surface-3)',
    ];

    /** Panel colours used as borders become the theme's line colour. */
    private const LINE = ['#2c3138', '#343a40', '#454d55', '#4a5568', '#2d3748', '#3a3f47'];

    private const WRAPPERS = ['.mining-manager-wrapper', '.mining-dashboard'];

    public function __construct(private string $root)
    {
    }

    public function build(): string
    {
        $sources = [
            'assets/css/mining-manager-dashboard.css' => file_get_contents("{$this->root}/src/Resources/assets/css/mining-manager-dashboard.css"),
        ];

        $views = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator("{$this->root}/src/Resources/views"));
        $paths = [];
        foreach ($views as $file) {
            if (str_ends_with((string) $file, '.blade.php')) {
                $paths[] = (string) $file;
            }
        }
        sort($paths);
        foreach ($paths as $path) {
            preg_match_all('#<style[^>]*>(.*?)</style>#s', file_get_contents($path), $m);
            if ($m[1]) {
                $sources[substr($path, strlen("{$this->root}/src/Resources/"))] = implode("\n", $m[1]);
            }
        }

        $out = [];
        foreach ($sources as $name => $css) {
            $rules = $this->overrides($css);
            if ($rules) {
                $out[] = "/* ---------- {$name} ---------- */\n" . implode("\n", $rules);
            }
        }

        return "/* ============================================\n"
            . "   Mining Manager - EVE-RO look, page-specific colours\n\n"
            . "   GENERATED by tools/build-theme-pages.php. Do not edit by hand:\n"
            . "   change the page's own styles and run the script again.\n\n"
            . "   Loaded after mm-theme.css with the EVE-RO look. Each rule swaps a\n"
            . "   colour of the original look written into a page's styles (purple\n"
            . "   accents, slate panels, purple tints) for the theme's own.\n"
            . "   ============================================ */\n\n"
            . implode("\n\n", $out) . "\n";
    }

    /** @return string[] */
    private function overrides(string $css): array
    {
        $css = preg_replace('#/\*.*?\*/#s', '', $css);
        // Keyframes hold no selectors worth overriding.
        $css = preg_replace('#@(-webkit-)?keyframes[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}#s', '', $css);
        // Blade output inside a style block is not CSS we can read.
        $css = preg_replace('#\{\{.*?\}\}|\{!!.*?!!\}|@(if|endif|else|foreach|endforeach)\b[^\n]*#s', '', $css);

        preg_match_all('#([^{}]+)\{([^{}]*)\}#', $css, $m, PREG_SET_ORDER);

        $rules = [];
        foreach ($m as [, $selector, $body]) {
            $selector = trim(preg_replace('#\s+#', ' ', $selector));
            if ($selector === '' || $selector[0] === '@' || preg_match('#^(from|to|\d+%)$#', $selector)) {
                continue;
            }

            $declarations = [];
            foreach (explode(';', $body) as $declaration) {
                if (!str_contains($declaration, ':')) {
                    continue;
                }
                [$property, $value] = array_map('trim', explode(':', $declaration, 2));
                $property = strtolower($property);
                $new = $this->mapDeclaration($property, $value);
                if ($new !== null) {
                    $declarations[$new[0]] = $new[1];
                }
            }

            if (!$declarations) {
                continue;
            }

            $scoped = $this->scope($selector);
            if (!$scoped) {
                continue;
            }

            $lines = [];
            foreach ($declarations as $property => $value) {
                $lines[] = "    {$property}: {$value} !important;";
            }
            $rules[] = implode(",\n", $scoped) . " {\n" . implode("\n", $lines) . "\n}";
        }

        return $rules;
    }

    /** @return array{0:string,1:string}|null */
    private function mapDeclaration(string $property, string $value): ?array
    {
        $value = trim(str_ireplace('!important', '', $value));
        $lower = strtolower(preg_replace('#\s+#', '', $value));

        $isBackground = str_starts_with($property, 'background');
        $isBorder = str_starts_with($property, 'border') || $property === 'outline' || $property === 'outline-color';
        $isColour = in_array($property, ['color', 'fill', 'stroke', 'caret-color', 'text-decoration-color'], true);
        $isShadow = in_array($property, ['box-shadow', 'text-shadow'], true);

        if (!$isBackground && !$isBorder && !$isColour && !$isShadow) {
            return null;
        }

        $changed = false;

        // Gradients go flat, in the first colour we recognise.
        if ($isBackground && str_contains($lower, 'gradient(')) {
            foreach (self::ACCENT as $hex => $var) {
                if (str_contains($lower, $hex)) {
                    return ['background', $hex === '#667eea' ? 'var(--mmx-blue-deep)' : $var];
                }
            }
            foreach (self::PANEL as $hex => $var) {
                if (str_contains($lower, $hex)) {
                    return ['background', $var];
                }
            }
            if (str_contains($lower, 'rgba(102,126,234')) {
                return ['background', 'rgba(0, 174, 255, 0.10)'];
            }

            return null;
        }

        $new = preg_replace_callback('#rgba?\(\s*102\s*,\s*126\s*,\s*234\s*(,\s*[\d.]+\s*)?\)#i', function ($c) use (&$changed) {
            $changed = true;
            return 'rgba(0, 174, 255' . ($c[1] ?? ', 1') . ')';
        }, $value);

        $new = preg_replace_callback('#\#[0-9a-fA-F]{3,8}\b#', function ($c) use (&$changed, $isBackground, $isBorder) {
            $hex = strtolower($c[0]);
            if (isset(self::ACCENT[$hex])) {
                $changed = true;
                return $isBackground && $hex === '#667eea' ? 'var(--mmx-blue-deep)' : self::ACCENT[$hex];
            }
            if ($isBackground && isset(self::PANEL[$hex])) {
                $changed = true;
                return self::PANEL[$hex];
            }
            if ($isBorder && in_array($hex, self::LINE, true)) {
                $changed = true;
                return 'var(--mmx-line)';
            }
            return $c[0];
        }, $new);

        return $changed ? [$property, $new] : null;
    }

    /** @return string[] */
    private function scope(string $selectorList): array
    {
        $out = [];
        foreach (explode(',', $selectorList) as $selector) {
            $selector = trim($selector);
            if ($selector === '' || preg_match('#^(:root|html|body)\b#', $selector)) {
                continue;
            }

            $wrapped = false;
            foreach (self::WRAPPERS as $wrapper) {
                if (str_contains($selector, $wrapper)) {
                    $wrapped = true;
                }
            }

            if ($wrapped) {
                $out[] = 'body ' . $selector;
                continue;
            }

            foreach (self::WRAPPERS as $wrapper) {
                $out[] = "body {$wrapper} {$selector}";
            }

            // Modals, tooltips and popovers are often moved to <body>.
            if (preg_match('#modal|tooltip|popover|toast#', $selector)) {
                $out[] = 'body:has(.mining-manager-wrapper) ' . $selector;
                $out[] = 'body:has(.mining-dashboard) ' . $selector;
            }
        }

        return array_values(array_unique($out));
    }
}

if (PHP_SAPI === 'cli' && realpath($argv[0] ?? '') === __FILE__) {
    $root = dirname(__DIR__);
    $css = (new ThemePagesBuilder($root))->build();
    file_put_contents("{$root}/src/Resources/assets/css/mm-theme-pages.css", $css);
    echo 'Wrote src/Resources/assets/css/mm-theme-pages.css (' . substr_count($css, '!important') . " overrides)\n";
}
